import type { Metadata } from 'next'

import { getPathname } from '@/i18n/navigation'
import { routing, type Locale } from '@/i18n/routing'

import { site } from './site'

export type Href = Parameters<typeof getPathname>[0]['href']

// The page's path in every locale. Slug pages pass their own map, because a translated slug
// differs per language (/fr/services/demenagement ↔ /en/services/moving).
export type LocalizedPaths = Record<Locale, string>

export const pathsFor = (href: Href): LocalizedPaths =>
  Object.fromEntries(
    routing.locales.map((locale) => [locale, getPathname({ locale, href })]),
  ) as LocalizedPaths

export const absoluteUrl = (path: string) => new URL(path, site.url).toString()

export const ogLocale = (locale: Locale) => (locale === 'fr' ? 'fr_CM' : 'en_CM')

type PageMeta = {
  locale: Locale
  title: string
  description: string
  // Every language the page exists in. A page that exists in fewer languages (an English-only
  // article) passes only those, plus `canonicalLocale` when the visited copy duplicates another.
  paths: Partial<LocalizedPaths>
  canonicalLocale?: Locale
  type?: 'website' | 'article'
  // Home only: the title is used as is, without the " · HandyMan Do IT" suffix.
  absoluteTitle?: boolean
}

const maxTitle = 65

// Collapses whitespace and trims to a length search engines show in full, at a word boundary.
export function clampDescription(text: string, max = 160) {
  const clean = text.replace(/\s+/g, ' ').trim()
  if (clean.length <= max) return clean
  const cut = clean.slice(0, max - 1)
  const space = cut.lastIndexOf(' ')
  return `${(space > max / 2 ? cut.slice(0, space) : cut).replace(/[\s,;:–—·-]+$/, '')}…`
}

/**
 * Title, description, canonical, hreflang alternates, Open Graph and Twitter tags for one page
 * (FR-SEO-01). French is the x-default (FR-I18N). The language switcher also follows these
 * alternates to the translated page, so a slug page that omits them would switch to a 404.
 * Share images come from the `opengraph-image` file next to each route (FR-SEO-04), which Next
 * merges over `openGraph.images`.
 */
export function pageMetadata({
  locale,
  title,
  description,
  paths,
  canonicalLocale = locale,
  type = 'website',
  absoluteTitle = false,
}: PageMeta): Metadata {
  const canonical = paths[canonicalLocale] ?? paths[locale]
  const xDefault = paths[routing.defaultLocale] ?? canonical
  // CMS titles generated by the SEO plugin already end with the site name (payload.config.ts).
  const ownTitle = title.replace(new RegExp(`\\s*[·|–-]\\s*${site.name}$`), '').trim() || title
  const desc = clampDescription(description)
  // Search results show about 60–65 characters. Long article and project titles drop the
  // " · HandyMan Do IT" suffix (the layout template) and are cut at a word; social cards keep
  // the whole title.
  const fitsWithSuffix = ownTitle.length + site.name.length + 3 <= maxTitle
  const tagTitle = absoluteTitle
    ? { absolute: title }
    : fitsWithSuffix
      ? ownTitle
      : { absolute: clampDescription(ownTitle, maxTitle) }
  return {
    title: tagTitle,
    description: desc,
    alternates: {
      canonical,
      languages: { ...paths, ...(xDefault ? { 'x-default': xDefault } : {}) },
    },
    openGraph: {
      type,
      siteName: site.name,
      title: ownTitle,
      description: desc,
      url: canonical,
      locale: ogLocale(locale),
      alternateLocale: routing.locales
        .filter((other) => other !== locale && paths[other])
        .map(ogLocale),
    },
    twitter: { card: 'summary_large_image', title: ownTitle, description: desc },
  }
}
